    `programCategoryName` VARCHAR(100) NULL,
    `programId` INT NULL,
    `programName` VARCHAR(100) NULL,
    `yearId` INT NULL,
    `yearName` VARCHAR(100) NULL,
    `semId` INT NULL,
    `semName` VARCHAR(100) NULL,
    `monthId` INT NULL,
