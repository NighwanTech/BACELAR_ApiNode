    `enrollmentNumber` VARCHAR(100) NULL,
    `fathersName` VARCHAR(255) NULL,
    `academicSessionId` INT NULL,
    `academicSessionName` VARCHAR(100) NULL,
    `sessionId` INT NULL,
    `sessionName` VARCHAR(100) NULL,
